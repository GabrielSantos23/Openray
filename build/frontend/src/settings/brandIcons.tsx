const BRAND_ICONS: Record<string, (props: { size: number }) => ReactNode> = {
  "brand:google": GoogleIcon,
  "brand:duckduckgo": DuckDuckGoIcon,
  "brand:bing": BingIcon,
  "brand:github": GitHubIcon,
  "brand:youtube": YouTubeIcon,
  "brand:wikipedia": WikipediaIcon,
};

/** Renders a fallback command's icon: brand SVG for web searches, Lucide for the rest. The
    canonical icon comes from the catalog so entries stored before a rename still render. */
export function FallbackSpecIcon({ spec, size = 14 }: { spec: FallbackCommandSpec; size?: number }) {
  const canonical = FALLBACK_CATALOG.find((entry) => entry.id === spec.id)?.icon ?? spec.icon;
  const Brand = BRAND_ICONS[canonical];
  if (Brand) return <>{Brand({ size })}</>;
  return <RaycastIcon name={canonical} size={size} />;
}
