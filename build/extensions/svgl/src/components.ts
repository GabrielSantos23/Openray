// Framework component generators (Vue/Svelte/Angular/Astro templates, mirroring the svgl
// extension's output shapes; the React path uses the svgr endpoint instead).

import { fetchSvg } from "./api";
import type { FlowKeyCapabilities } from "@flowkey-mini/native-sdk";

const showComponentFetchError = (title: string, error: unknown): Error =>
  error instanceof Error ? new Error(`${title}: ${error.message}`) : new Error(title);

/** Pulls `<style>` bodies out of an SVG document for Vue/Svelte templates. */
export function parseSvgContent(content: string, framework: "Vue" | "Svelte") {
  let working = content.includes("<?xml") ? content.replace(/<\?xml[^>]*\?>/i, "") : content;
  const styleTagRegex = /<style[^>]*>([\s\S]*?)<\/style>/gi;
  const styles: string[] = [];
  let matched: RegExpExecArray | null;
  while ((matched = styleTagRegex.exec(working)) !== null) {
    styles.push(matched[1]);
  }
  const templateContent = working.replace(styleTagRegex, "");
  const componentStyle = styles.length
    ? `<style${framework === "Vue" ? " scoped" : ""}>\n${styles.join("\n")}\n</style>`
    : "";
  return { componentStyle, templateContent };
}

export async function vueOrSvelteComponent(
  capabilities: FlowKeyCapabilities,
  lang: string,
  url: string,
  framework: "Vue" | "Svelte",
): Promise<string> {
  try {
    const svg = await fetchSvg(capabilities, url);
    const { templateContent, componentStyle } = parseSvgContent(svg, framework);
    if (framework === "Vue") {
      return `<script setup${lang ? ` lang="${lang}"` : ""}></script>
<template>
 ${templateContent}
</template>

    ${componentStyle}
    `;
    }
    return `<script${lang ? ` lang="${lang}"` : ""}></script>
 ${templateContent}

${componentStyle}
    `;
  } catch (error) {
    throw showComponentFetchError(`Failed to fetch ${framework.toLowerCase()} component`, error);
  }
}

export async function angularComponent(
  capabilities: FlowKeyCapabilities,
  url: string,
  componentName: string,
): Promise<string> {
  try {
    const svg = await fetchSvg(capabilities, url);
    const updatedSvg = svg.replace(
      /<svg([^>]*)>/,
      `<svg$1 [attr.width]="size.width" [attr.height]="size.height">`,
    );
    return `
  /**
   * -------------------------------------------------------------------------
   * This Angular standalone component was generated by svgl.app
   * 🧩 A beautiful library with SVG logos
   * -------------------------------------------------------------------------
   */
  import { Component, Input } from '@angular/core';
  @Component({
    selector: 'svg-${componentName}',
    standalone: true,
    template: \`
      ${updatedSvg.trim()}
    \`,
  })
  export class ${componentName}Component {
    @Input({ required: true }) size: { width: number; height: number };
  }
  `;
  } catch (error) {
    throw showComponentFetchError("Failed to fetch angular component", error);
  }
}

export async function astroComponent(capabilities: FlowKeyCapabilities, url: string): Promise<string> {
  try {
    const svg = await fetchSvg(capabilities, url);
    return svg
      .replace(/\s*(width|height)="[^"]*"/gi, "")
      .replace(/\s*(width|height)='[^']*'/gi, "")
      .replace(/\s*(width|height)=\{[^}]*\}/gi, "")
      .replace(/<svg([^>]*)>/i, (_match, attrs: string) => {
        const cleanedAttrs = attrs.replace(/\s*\{?\.\.\.Astro\.props\}?\s*/i, "");
        return `<svg ${cleanedAttrs} {...Astro.props}>`;
      })
      .trim();
  } catch (error) {
    throw showComponentFetchError("Failed to fetch astro component", error);
  }
}

export function shadcnInstallCommand(title: string, packageManager: string): string {
  const slug = title
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  const runners: Record<string, string> = {
    pnpm: "pnpm dlx",
    npm: "npx",
    yarn: "yarn",
    bun: "bunx --bun",
  };
  return `${runners[packageManager] ?? runners.pnpm} shadcn@latest add @svgl/${slug}`;
}
